//! The global coordinator owns deletion intent; this module owns its file handles.

use super::*;

impl OwnerStore {
    /// Inspect a closed backup without migrating, creating or repairing it.
    pub fn inspect_backup(path: &Path) -> AppResult<usize> {
        let conn = connection::open_reader(path)?;
        migrations::inspect(&conn)
    }

    pub fn close_admission(&self) -> AppResult<u64> {
        self.run(|conn| {
            let tx = conn.transaction().during("close owner admission")?;
            let changed = tx.execute("UPDATE owner_meta SET epoch=epoch+1,admission_open=0 WHERE singleton=1 AND epoch<9223372036854775807", [])
                .during("advance owner purge epoch")?;
            if changed != 1 { return Err(not_ready("owner epoch exhausted")); }
            let epoch: i64 = tx.query_row("SELECT epoch FROM owner_meta WHERE singleton=1", [], |r| r.get(0)).during("read owner purge epoch")?;
            tx.commit().during("commit owner admission closure")?;
            epoch_value(epoch)
        })
    }

    /// Startup uses the durable global journal before admitting any producer.
    pub fn synchronize_epoch(&self, epoch: u64) -> AppResult<()> {
        let epoch = i64::try_from(epoch).map_err(|_| not_ready("owner epoch exhausted"))?;
        self.run(move |conn| {
            conn.execute(
                "UPDATE owner_meta SET epoch=MAX(epoch,?1),admission_open=0 WHERE singleton=1",
                [epoch],
            )
            .during("synchronize owner purge epoch")?;
            Ok(())
        })
    }

    pub fn reopen_admission(&self) -> AppResult<()> {
        self.run(|conn| {
            conn.execute(
                "UPDATE owner_meta SET admission_open=1 WHERE singleton=1",
                [],
            )
            .during("reopen owner admission")?;
            Ok(())
        })
    }

    pub fn flush(&self) -> AppResult<()> {
        self.run(|conn| {
            let busy: u32 = conn
                .query_row("PRAGMA wal_checkpoint(TRUNCATE)", [], |r| r.get(0))
                .during("flush owner store")?;
            if busy != 0 {
                return Err(not_ready("owner checkpoint is busy"));
            }
            Ok(())
        })
    }

    pub fn shutdown(&self) -> AppResult<()> {
        let mut guard = self.runtime.write().unwrap_or_else(|p| p.into_inner());
        if let Some(runtime) = guard.take() {
            // Write lock drains reads and all writer replies. Normal shutdown does
            // not change durable admission; a pending purge remains closed on restart.
            runtime.stop()?;
        }
        Ok(())
    }

    /// Exact inventory generated by this store, including pre-migration backups.
    /// It deliberately excludes external exports and source projects.
    pub fn owned_files(&self) -> AppResult<Vec<PathBuf>> {
        let mut paths = vec![
            self.path.clone(),
            companion(&self.path, "-wal"),
            companion(&self.path, "-shm"),
            companion(&self.path, "-journal"),
        ];
        if let Some(parent) = self.path.parent() {
            for entry in
                std::fs::read_dir(parent).map_err(|source| crate::error::AppError::File {
                    operation: "list owner files",
                    path: parent.into(),
                    source,
                })?
            {
                let entry = entry.map_err(|source| crate::error::AppError::File {
                    operation: "list owner file",
                    path: parent.into(),
                    source,
                })?;
                let name = entry.file_name().to_string_lossy().into_owned();
                let base = ["-wal", "-shm", "-journal"]
                    .into_iter()
                    .find_map(|suffix| name.strip_suffix(suffix))
                    .unwrap_or(&name);
                if let Some(id) = base
                    .strip_prefix("owner-workspace.pre-migration-")
                    .and_then(|s| s.strip_suffix(".sqlite"))
                {
                    if uuid::Uuid::parse_str(id).is_ok() {
                        paths.push(entry.path());
                    }
                }
            }
        }
        Ok(paths)
    }

    /// Requires a durable global purge intent and closed admission. A failed deletion
    /// leaves this same store unavailable so the coordinator can retry safely.
    pub fn reset_after_purge(&self, epoch: u64) -> AppResult<()> {
        if epoch > i64::MAX as u64 {
            return Err(not_ready("owner epoch exhausted"));
        }
        let mut guard = self.runtime.write().unwrap_or_else(|p| p.into_inner());
        if let Some(runtime) = guard.as_ref() {
            let (open, prior): (bool, i64) = runtime.run(|conn| {
                conn.query_row(
                    "SELECT admission_open,epoch FROM owner_meta WHERE singleton=1",
                    [],
                    |r| Ok((r.get(0)?, r.get(1)?)),
                )
                .during("check owner purge admission")
            })?;
            if open {
                return Err(not_ready("close owner admission before purge"));
            }
            if epoch < epoch_value(prior)? {
                return Err(not_ready("purge epoch must not move backwards"));
            }
        }
        if let Some(runtime) = guard.take() {
            runtime.stop()?;
        }
        *lock(&self.failure) = Some("owner purge is incomplete".into());
        for path in self.owned_files()? {
            match std::fs::remove_file(&path) {
                Ok(()) => {}
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(source) => {
                    return Err(crate::error::AppError::File {
                        operation: "remove owned owner store file",
                        path,
                        source,
                    })
                }
            }
        }
        let runtime = Runtime::open(&self.path)?;
        let epoch = i64::try_from(epoch).map_err(|_| not_ready("owner epoch exhausted"))?;
        runtime.run(move |conn| {
            conn.execute(
                "UPDATE owner_meta SET epoch=?1,admission_open=0 WHERE singleton=1",
                [epoch],
            )
            .during("initialize purged owner epoch")?;
            Ok(())
        })?;
        *guard = Some(runtime);
        *lock(&self.failure) = None;
        Ok(())
    }
}

fn companion(path: &Path, suffix: &str) -> PathBuf {
    let mut name = path.as_os_str().to_owned();
    name.push(suffix);
    PathBuf::from(name)
}
