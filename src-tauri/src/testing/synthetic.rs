//! Deterministic event corpora for development screens and scale tests.
//!
//! Every row is labelled `synthetic` at construction and still has to pass
//! through `Sanitizer` before a repository accepts it.

use serde::{Deserialize, Serialize};
use std::str::FromStr;

use crate::domain::{
    classify, entity_type_of, now_ms, Category, ClassifierContext, Entity, EntityType, EventType,
    NormalizedEvent, Relationship, RelationshipKind, Severity,
};
use crate::error::{AppError, AppResult};
use crate::privacy::{Sanitized, Sanitizer};
use crate::storage::{entity_repository, Db};

mod demo;

/// A named deterministic corpus.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SyntheticProfile {
    Day,
    Week,
    Burst,
    Demo,
    TenThousand,
    HundredThousand,
    OneMillion,
}

impl SyntheticProfile {
    /// Rows generated by this profile.
    pub const fn rows(self) -> usize {
        match self {
            Self::Day => 2_000,
            Self::Week => 10_000,
            Self::Burst => 40,
            Self::Demo => demo::ROWS,
            Self::TenThousand => 10_000,
            Self::HundredThousand => 100_000,
            Self::OneMillion => 1_000_000,
        }
    }
}

impl FromStr for SyntheticProfile {
    type Err = AppError;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value {
            "day" => Ok(Self::Day),
            "week" => Ok(Self::Week),
            "burst" => Ok(Self::Burst),
            "demo" => Ok(Self::Demo),
            "10k" => Ok(Self::TenThousand),
            "100k" => Ok(Self::HundredThousand),
            "1m" => Ok(Self::OneMillion),
            _ => Err(AppError::InvalidInput {
                what: "profile",
                reason: "expected day, week, burst, demo, 10k, 100k, or 1m".to_owned(),
            }),
        }
    }
}

/// Generate a profile with byte-stable content for `seed` and `end_at`.
pub fn profile(
    profile: SyntheticProfile,
    seed: u64,
    end_at: i64,
) -> Vec<Sanitized<NormalizedEvent>> {
    if profile == SyntheticProfile::Demo {
        // The story is fixed relative to its end time; the random seed is
        // deliberately irrelevant, unlike the scale-test corpora below.
        return demo::profile(end_at);
    }
    let mut random = Lcg::new(seed);
    let rows = profile.rows();
    let spacing = match profile {
        SyntheticProfile::Burst => 1_000,
        SyntheticProfile::Demo => 0,
        SyntheticProfile::Day => 43_200,
        SyntheticProfile::Week | SyntheticProfile::TenThousand => 60_000,
        SyntheticProfile::HundredThousand | SyntheticProfile::OneMillion => 5_000,
    };
    let start = end_at.saturating_sub(
        i64::try_from(rows.saturating_sub(1))
            .unwrap_or(i64::MAX)
            .saturating_mul(spacing),
    );
    let sanitizer = Sanitizer::new();
    (0..rows)
        .map(|index| {
            let stream_seed = random.next().wrapping_add(index as u64);
            let timestamp = start.saturating_add(
                i64::try_from(index)
                    .unwrap_or(i64::MAX)
                    .saturating_mul(spacing),
            );
            let mut event = super::synthetic_event(stream_seed, timestamp);
            let context = ClassifierContext {
                automatic_service: event.category == Category::Service && index % 97 == 0,
                relevant_driver: event.category == Category::Driver && index % 89 == 0,
                checkpoint_port: event.entity_type == EntityType::Port && index % 83 == 0,
                unexpected_shutdown: false,
                // The synthetic corpora model a mixed machine, not a browser
                // session, so nothing in them is a helper subprocess.
                browser_subprocess: false,
            };
            event.importance = classify(&event, &context);
            sanitizer.sanitize(event).0
        })
        .collect()
}

/// Seed a database through the production writer, optionally adding a small
/// deterministic structural graph for investigation and visualization work.
/// This is the implementation behind the developer tool's `--profile` and
/// `--relations` selectors; it is unavailable in a normal release build.
pub fn seed(
    db: &Db,
    profile_name: &str,
    random_seed: u64,
    end_at: i64,
    relations: bool,
) -> AppResult<Vec<i64>> {
    let selected: SyntheticProfile = profile_name.parse()?;
    let generated = profile(selected, random_seed, end_at);
    let relation_inputs: Vec<_> = generated.iter().map(|event| event.get().clone()).collect();
    let ids = db.insert_events(generated)?;
    if selected == SyntheticProfile::Demo {
        // The demo is a connected, explicitly disclosed story even when the
        // optional relation switch for generic scale corpora is off.
        let edges = demo::relationships(&ids, &relation_inputs)?;
        db.write(move |conn| {
            for edge in &edges {
                entity_repository::insert_relationship(conn, edge)?;
            }
            Ok(())
        })?;
    } else if relations {
        let relation_ids = ids.clone();
        db.write(move |conn| {
            for (event, event_id) in relation_inputs.iter().zip(&relation_ids) {
                let Some(kind) = synthetic_relationship_kind(event.category) else {
                    continue;
                };
                for target_id in &event.related_entity_ids {
                    let Some(entity_type) = entity_type_of(target_id) else {
                        continue;
                    };
                    entity_repository::upsert(
                        conn,
                        &Entity {
                            id: target_id.clone(),
                            entity_type,
                            display_name: target_id.clone(),
                            first_seen: event.timestamp,
                            last_seen: event.timestamp,
                            metadata: None,
                        },
                    )?;
                    entity_repository::insert_relationship(
                        conn,
                        &Relationship {
                            source_id: event.entity_id.clone(),
                            target_id: target_id.clone(),
                            kind,
                            event_id: Some(*event_id),
                            recorded_at: event.timestamp,
                        },
                    )?;
                }
            }
            Ok(())
        })?;
    }
    Ok(ids)
}

fn synthetic_relationship_kind(category: Category) -> Option<RelationshipKind> {
    match category {
        Category::Process => Some(RelationshipKind::ListensOn),
        Category::Docker => Some(RelationshipKind::Publishes),
        Category::Configuration | Category::Filesystem => Some(RelationshipKind::ConfigOf),
        _ => None,
    }
}

/// One supported simulation event with a stable shape for the requested kind.
pub fn one(kind: &str) -> AppResult<Sanitized<NormalizedEvent>> {
    let seed = match kind {
        "driver_update" => 6,
        "port_change" => 1,
        "process_crash" => 5,
        "dns_change" => 4,
        "docker_restart" => 8,
        "config_diff" => 3,
        _ => {
            return Err(AppError::InvalidInput {
                what: "kind",
                reason: "that simulation kind is not supported".to_owned(),
            })
        }
    };
    let mut event = super::synthetic_event(seed, now_ms());
    event.source_collector = "synthetic".to_owned();
    let context = match kind {
        "driver_update" => {
            event.category = Category::Driver;
            event.event_type = EventType::Updated;
            event.entity_type = EntityType::Driver;
            event.entity_id = "driver:nvlddmkm".into();
            event.entity_display_name = "NVIDIA display driver".into();
            event.before = Some(serde_json::json!({ "version": "31.0.15.5212" }));
            event.after = Some(serde_json::json!({ "version": "32.0.15.6094" }));
            event.metadata = Some(serde_json::json!({ "service": "nvlddmkm", "class": "display" }));
            event.user_friendly_summary = "NVIDIA display driver updated".into();
            ClassifierContext {
                relevant_driver: true,
                ..Default::default()
            }
        }
        "port_change" => {
            event.category = Category::Network;
            event.event_type = EventType::Closed;
            event.entity_type = EntityType::Port;
            event.entity_id = "port:tcp:0.0.0.0:3000".into();
            event.entity_display_name = "TCP port 3000".into();
            event.before = Some(serde_json::json!({ "listening": true, "process": "api.exe" }));
            event.after = Some(serde_json::json!({ "listening": false }));
            event.metadata = Some(serde_json::json!({ "port": 3000, "protocol": "tcp" }));
            event.related_entity_ids = vec!["process:api".into()];
            event.user_friendly_summary = "Port 3000 stopped listening".into();
            ClassifierContext {
                checkpoint_port: true,
                ..Default::default()
            }
        }
        "process_crash" => {
            event.category = Category::Process;
            event.event_type = EventType::Failed;
            event.entity_type = EntityType::Process;
            event.entity_id = "process:api".into();
            event.entity_display_name = "api.exe".into();
            event.severity = Severity::Error;
            event.before = Some(serde_json::json!({ "running": true, "pid": 4242 }));
            event.after = Some(serde_json::json!({ "running": false, "exit_code": 1 }));
            event.metadata = Some(serde_json::json!({ "pid": 4242, "unexpected": true }));
            event.user_friendly_summary = "api.exe stopped unexpectedly".into();
            ClassifierContext::default()
        }
        "dns_change" => {
            event.category = Category::Network;
            event.event_type = EventType::ConfigurationChanged;
            event.entity_type = EntityType::Adapter;
            event.entity_id = "adapter:wifi".into();
            event.entity_display_name = "Wi-Fi".into();
            event.before = Some(serde_json::json!({ "dns": ["1.1.1.1"] }));
            event.after = Some(serde_json::json!({ "dns": ["192.168.1.1"] }));
            event.metadata = Some(serde_json::json!({ "setting": "dns" }));
            event.user_friendly_summary = "DNS servers changed on Wi-Fi".into();
            ClassifierContext::default()
        }
        "docker_restart" => {
            event.category = Category::Docker;
            event.event_type = EventType::Restarted;
            event.entity_type = EntityType::Container;
            event.entity_id = "container:api000000001".into();
            event.entity_display_name = "api".into();
            event.before = Some(serde_json::json!({ "status": "exited" }));
            event.after = Some(serde_json::json!({ "status": "running" }));
            event.metadata = Some(serde_json::json!({ "compose_file": "docker-compose.yml" }));
            event.user_friendly_summary = "api container restarted".into();
            ClassifierContext::default()
        }
        "config_diff" => {
            event.category = Category::Configuration;
            event.event_type = EventType::Modified;
            event.entity_type = EntityType::File;
            event.entity_id = "file:synthetic-dotenv".into();
            event.entity_display_name = ".env".into();
            event.before = Some(serde_json::json!({ "PORT": "3000" }));
            event.after = Some(serde_json::json!({ "PORT": "8080" }));
            event.metadata = Some(serde_json::json!({ "file": ".env", "keys": ["PORT"] }));
            event.related_entity_ids = vec!["process:api".into()];
            event.user_friendly_summary = "PORT changed in .env".into();
            ClassifierContext::default()
        }
        _ => ClassifierContext::default(),
    };
    event.technical_summary = format!("synthetic {kind}: {}", event.entity_id);
    event.importance = classify(&event, &context);
    Ok(Sanitizer::new().sanitize(event).0)
}

#[derive(Debug, Clone, Copy)]
struct Lcg(u64);

impl Lcg {
    const fn new(seed: u64) -> Self {
        Self(seed)
    }

    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        self.0
    }
}

#[cfg(test)]
#[allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]
mod tests {
    use super::*;
    use crate::storage::SqlContext;

    #[test]
    fn profiles_are_deterministic_and_always_label_the_source() {
        let a = profile(SyntheticProfile::Burst, 42, 1_000_000);
        let b = profile(SyntheticProfile::Burst, 42, 1_000_000);
        assert_eq!(a, b);
        assert_eq!(a.len(), 40);
        assert!(a
            .iter()
            .all(|event| event.get().source_collector == "synthetic"));
    }

    #[test]
    fn only_documented_simulation_kinds_are_accepted() {
        let cases = [
            (
                "driver_update",
                Category::Driver,
                EventType::Updated,
                EntityType::Driver,
            ),
            (
                "port_change",
                Category::Network,
                EventType::Closed,
                EntityType::Port,
            ),
            (
                "process_crash",
                Category::Process,
                EventType::Failed,
                EntityType::Process,
            ),
            (
                "dns_change",
                Category::Network,
                EventType::ConfigurationChanged,
                EntityType::Adapter,
            ),
            (
                "docker_restart",
                Category::Docker,
                EventType::Restarted,
                EntityType::Container,
            ),
            (
                "config_diff",
                Category::Configuration,
                EventType::Modified,
                EntityType::File,
            ),
        ];
        for (kind, category, event_type, entity_type) in cases {
            let event = one(kind).unwrap();
            let event = event.get();
            assert_eq!(
                (event.category, event.event_type, event.entity_type),
                (category, event_type, entity_type)
            );
            assert_eq!(event.source_collector, "synthetic");
            assert!(event.before.is_some() && event.after.is_some() && event.metadata.is_some());
        }
        assert!(one("anything_else").is_err());
    }

    #[test]
    fn profile_selectors_parse_and_relations_are_optional() {
        assert_eq!(
            "10k".parse::<SyntheticProfile>().unwrap(),
            SyntheticProfile::TenThousand
        );
        assert!("million".parse::<SyntheticProfile>().is_err());

        let db = Db::open_in(&crate::testing::temp_dir("synthetic-relations"))
            .expect("open synthetic database");
        let ids = seed(&db, "burst", 42, 1_000_000, true).expect("seed with relations");
        assert_eq!(ids.len(), 40);
        let count: i64 = db
            .read(|conn| {
                conn.query_row("SELECT COUNT(*) FROM entity_relationships", [], |row| {
                    row.get(0)
                })
                .during("count synthetic relationships")
            })
            .expect("count synthetic relationships");
        assert!(count > 0);
    }
}
