<#
.SYNOPSIS
  Verifies the installer pair and reviewed notice payload.

.DESCRIPTION
  The Tauri NSIS output is the raw artifact. The published download is copied
  to the stable WhatChanged-Setup-x64.exe name. This script is intentionally
  read-only: it validates both files and the checksum manifest generated by
  release.ps1 without installing or executing an untrusted binary. The NSIS
  script must name the notice resource; installed-file inspection remains a
  separate manual acceptance gate.
#>
[CmdletBinding()]
param(
    [string]$RawInstaller,
    [string]$PublishedInstaller,
    [string]$ChecksumsFile,
    [string]$NoticesFile,
    [string]$NsisScript,
    [int]$MaximumSizeMb = 25
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot

function Resolve-File([string]$Path, [string]$Label) {
    if ([string]::IsNullOrWhiteSpace($Path)) { throw "installer verification: $Label path was not supplied" }
    $item = Get-Item -LiteralPath $Path -ErrorAction SilentlyContinue
    if (-not $item -or $item.PSIsContainer) { throw "installer verification: $Label does not exist: $Path" }
    return $item
}

function Get-ManifestPath([System.IO.FileInfo]$Item) {
    $rootFull = [System.IO.Path]::GetFullPath($root).TrimEnd('\', '/')
    $itemFull = [System.IO.Path]::GetFullPath($Item.FullName)
    $prefix = $rootFull + [System.IO.Path]::DirectorySeparatorChar
    if ($itemFull.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        return $itemFull.Substring($prefix.Length).Replace('\', '/')
    }
    return $itemFull.Replace('\', '/')
}

$targetDir = if ($env:CARGO_TARGET_DIR) {
    if ([System.IO.Path]::IsPathRooted($env:CARGO_TARGET_DIR)) {
        $env:CARGO_TARGET_DIR
    } else {
        Join-Path $root $env:CARGO_TARGET_DIR
    }
} else {
    Join-Path $root 'src-tauri/target'
}
if ([string]::IsNullOrWhiteSpace($RawInstaller)) {
    $rawDir = Join-Path ([System.IO.Path]::GetFullPath($targetDir)) 'release/bundle/nsis'
    $RawInstaller = (Get-ChildItem -LiteralPath $rawDir -Filter '*-setup.exe' -File -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1).FullName
}
if ([string]::IsNullOrWhiteSpace($PublishedInstaller)) {
    $PublishedInstaller = Join-Path $root 'dist-installer/WhatChanged-Setup-x64.exe'
}
if ([string]::IsNullOrWhiteSpace($ChecksumsFile)) {
    $ChecksumsFile = Join-Path $root 'dist-installer/SHA256SUMS.txt'
}
if ([string]::IsNullOrWhiteSpace($NoticesFile)) {
    $NoticesFile = Join-Path $root 'dist-installer/THIRD_PARTY_NOTICES.txt'
}
if ([string]::IsNullOrWhiteSpace($NsisScript)) {
    $NsisScript = Join-Path $targetDir 'release/nsis/x64/installer.nsi'
}

$raw = Resolve-File $RawInstaller 'raw installer'
$published = Resolve-File $PublishedInstaller 'published installer'
$checksums = Resolve-File $ChecksumsFile 'checksum manifest'
$notices = Resolve-File $NoticesFile 'reviewed third-party notices'
$nsis = Resolve-File $NsisScript 'generated NSIS script'

& node (Join-Path $root 'scripts/generate-third-party-notices.mjs') --check
if ($LASTEXITCODE -ne 0) {
    throw 'installer verification: notice review or release-input parity check failed'
}
$generatedNotice = Resolve-File (Join-Path $root 'dist-installer/THIRD_PARTY_NOTICES.txt') 'generated reviewed notices'
if ((Get-FileHash -LiteralPath $notices.FullName -Algorithm SHA256).Hash -ne
    (Get-FileHash -LiteralPath $generatedNotice.FullName -Algorithm SHA256).Hash) {
    throw 'installer verification: supplied notice differs from the generated reviewed payload'
}
if ($notices.Length -le 100) {
    throw 'installer verification: reviewed third-party notices are empty or implausibly short'
}
$noticeText = Get-Content -LiteralPath $notices.FullName -Raw
if ($noticeText -match '(?m)^PENDING - NOT FOR RELEASE$') {
    throw 'installer verification: build-only pending notice placeholder cannot be released'
}
& node (Join-Path $root 'scripts/verify-nsis-notice-copy.mjs') $nsis.FullName $generatedNotice.FullName
if ($LASTEXITCODE -ne 0) {
    throw 'installer verification: generated NSIS script does not copy the reviewed notice resource'
}

if ($raw.Name -notmatch '^What Changed_[0-9]+\.[0-9]+\.[0-9]+(?:[-+][0-9A-Za-z.-]+)?_x64-setup\.exe$') {
    throw "installer verification: unexpected raw installer name '$($raw.Name)'"
}
if ($published.Name -ne 'WhatChanged-Setup-x64.exe') {
    throw "installer verification: unexpected published installer name '$($published.Name)'"
}
$cargoManifest = Join-Path $root 'src-tauri/Cargo.toml'
$cargoVersion = Select-String -LiteralPath $cargoManifest -Pattern '^version\s*=\s*"([^"]+)"' |
    Select-Object -First 1
if ($cargoVersion) {
    $expectedVersion = $cargoVersion.Matches[0].Groups[1].Value
    $expectedRawName = 'What Changed_' + $expectedVersion + '_x64-setup.exe'
    if ($raw.Name -ne $expectedRawName) {
        throw "installer verification: raw installer '$($raw.Name)' does not match Cargo version $expectedVersion"
    }
}

$maximumBytes = [int64]$MaximumSizeMb * 1MB
foreach ($item in @($raw, $published)) {
    if ($item.Length -le 0) { throw "installer verification: $($item.FullName) is empty" }
    if ($item.Length -gt $maximumBytes) {
        throw "installer verification: $($item.Name) is $($item.Length) bytes, above ${MaximumSizeMb} MB budget"
    }
    $version = $item.VersionInfo
    if ($version.ProductName -ne 'What Changed') {
        throw "installer verification: $($item.Name) reports product '$($version.ProductName)'"
    }
}

$rawHash = (Get-FileHash -LiteralPath $raw.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
$publishedHash = (Get-FileHash -LiteralPath $published.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
if ($rawHash -ne $publishedHash) {
    throw "installer verification: published installer bytes differ from the raw Tauri artifact"
}
$rawRelative = Get-ManifestPath $raw
$publishedRelative = Get-ManifestPath $published
$noticeRelative = Get-ManifestPath $notices
$noticeHash = (Get-FileHash -LiteralPath $notices.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
$manifest = Get-Content -LiteralPath $checksums.FullName |
    Where-Object { -not [string]::IsNullOrWhiteSpace($_) } |
    ForEach-Object { $_.Trim() }
if ($manifest.Count -ne 3) {
    throw "installer verification: checksum manifest must contain exactly three artifact entries"
}

$manifestEntries = @{}
foreach ($line in $manifest) {
    if ($line -notmatch '^(?<hash>[0-9a-fA-F]{64})\s+(?<path>.+)$') {
        throw "installer verification: malformed checksum manifest entry '$line'"
    }
    $manifestPath = $Matches.path.Trim().Replace('\', '/')
    if ($manifestEntries.ContainsKey($manifestPath)) {
        throw "installer verification: duplicate checksum manifest entry '$manifestPath'"
    }
    $manifestEntries[$manifestPath] = $Matches.hash.ToLowerInvariant()
}

$expectedEntries = [ordered]@{
    $rawRelative = $rawHash
    $publishedRelative = $publishedHash
    $noticeRelative = $noticeHash
}
if ($manifestEntries.Count -ne $expectedEntries.Count) {
    throw "installer verification: checksum manifest contains unexpected artifact entries"
}
foreach ($entry in $expectedEntries.GetEnumerator()) {
    if (-not $manifestEntries.ContainsKey($entry.Key)) {
        throw "installer verification: checksum manifest is missing $($entry.Key)"
    }
    if ($manifestEntries[$entry.Key] -ne $entry.Value) {
        throw "installer verification: checksum mismatch for $($entry.Key)"
    }
}

Write-Host "installer verification: PASS" -ForegroundColor Green
Write-Host ("  raw       {0}  {1} bytes  sha256 {2}" -f $raw.Name, $raw.Length, $rawHash)
Write-Host ("  published {0}  {1} bytes  sha256 {2}" -f $published.Name, $published.Length, $publishedHash)
Write-Host ("  notices   {0}  {1} bytes" -f $notices.Name, $notices.Length)
exit 0
